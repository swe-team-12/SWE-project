import type { Href } from "expo-router";

interface NotificationTarget {
  type?: string;
  data?: Record<string, unknown> | null;
}

export type NotificationTargetKind =
  | "case"
  | "order"
  | "tickets"
  | "event"
  | "manage"
  | "scanner"
  | "admin";

export type NotificationHref = Href;

function text(data: Record<string, unknown>, key: string): string | undefined {
  const value = data[key];
  return typeof value === "string" && value ? value : undefined;
}

// Changes that only the organizer's side (owner or event staff) is told about.
const ORGANIZER_CHANGES = new Set([
  "paid_sales_suspended",
  "paid_sales_unsuspended",
  "staff_assigned",
]);
// The public page of such an event is not available to ticket holders.
const HIDDEN_EVENT_CHANGES = new Set(["suspended", "unpublished"]);

/**
 * Where a notification leads: the related case, order, ticket wallet or event.
 * Organizer-facing notifications open the event's management page, attendee
 * ones the public page, and a new report opens the admin console.
 */
export function notificationTarget(
  notification: NotificationTarget,
): { kind: NotificationTargetKind; href: Href } | undefined {
  const data = notification.data ?? {};
  const type = notification.type;
  const change = text(data, "change");
  const caseId = text(data, "case_id");
  const orderId = text(data, "order_id");
  const eventId = text(data, "event_id");
  if (caseId)
    return {
      kind: "case",
      href: { pathname: "/support/[id]", params: { id: caseId } },
    };
  if (type === "event_report" && change === "event_reported")
    return { kind: "admin", href: "/admin" };
  if (type === "ticket_delivered") return { kind: "tickets", href: "/tickets" };
  if (orderId)
    return {
      kind: "order",
      // Typed routes are generated by the dev server and may predate the
      // order detail screen, hence the plain path.
      href: `/orders/${encodeURIComponent(orderId)}` as Href,
    };
  if (!eventId) return undefined;
  const manage: { kind: NotificationTargetKind; href: Href } = {
    kind: "manage",
    href: { pathname: "/organizer/events/[id]", params: { id: eventId } },
  };
  if (type === "payout_status" || type === "activation_status") return manage;
  if (type === "event_updated" && change) {
    if (change === "staff_assigned" && data.role === "check_in")
      return { kind: "scanner", href: "/scanner" };
    // Only the owner's copy of a suspension carries the paid-sales flag.
    const ownerCopy = "paid_sales_suspended" in data;
    if (
      ORGANIZER_CHANGES.has(change) ||
      (ownerCopy && (change === "suspended" || change === "unsuspended"))
    )
      return manage;
    if (HIDDEN_EVENT_CHANGES.has(change))
      return { kind: "tickets", href: "/tickets" };
    if (change === "staff_removed") return undefined;
  }
  return {
    kind: "event",
    href: { pathname: "/events/[id]", params: { id: eventId } },
  };
}

export function notificationHref(
  notification: NotificationTarget,
): NotificationHref | undefined {
  return notificationTarget(notification)?.href;
}
